type colKind int

const (
	colString colKind = iota
	colU8
	colU16
	colU32
	colI32
	colBool
	colStringList
	colU32List
	colPointList
	colPoint
	colRecordList
)

type col struct {
	goName   string
	rsName   string
	leanName string
	kind     colKind
	sub      []col
	subName  string
}

type rowValues []any

type table struct {
	name             string
	goName           string
	rsName           string
	leanName         string
	goType           string
	rsType           string
	leanType         string
	leanOpaque       bool
	cols             []col
	rows             []rowValues
	rustPublicStatic bool
}

func (t *table) goRowType() string {
	if t.goType != "" {
		return t.goType
	}
	return exportName(t.name)
}

func (t *table) rsRowType() string {
	if t.rsType != "" {
		return t.rsType
	}
	return exportName(t.name)
}

func (t *table) leanRowType() string {
	if t.leanType != "" {
		return t.leanType
	}
	return exportName(t.name)
}

func exportName(s string) string {
	parts := strings.FieldsFunc(s, func(r rune) bool { return r == '-' || r == '_' })
	var b strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]))
		b.WriteString(p[1:])
	}
	return b.String()
}

func (t *table) renderGo() ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by tools/specgen; DO NOT EDIT.\n\npackage gen\n\n")
	writeGoDecls(&b, t)
	fmt.Fprintf(&b, "var %s = []%s{", t.goName, t.goRowType())
	for _, row := range t.rows {
		b.WriteString("\n\t{")
		for i, c := range t.cols {
			if i > 0 {
				b.WriteString(", ")
			}
			lit, err := goValue(c, row[i])
			if err != nil {
				return nil, fmt.Errorf("%s: %w", t.name, err)
			}
			b.WriteString(lit)
		}
		b.WriteString("},")
	}
	if len(t.rows) > 0 {
		b.WriteString("\n")
	}
	b.WriteString("}\n")
	return []byte(b.String()), nil
}

func writeGoDecls(b *strings.Builder, t *table) {
	for _, c := range t.cols {
		if c.kind != colRecordList {
			continue
		}
		fmt.Fprintf(b, "type %s struct {\n", c.subName)
		for _, sc := range c.sub {
			fmt.Fprintf(b, "\t%s %s\n", sc.goName, goFieldType(sc))
		}
		b.WriteString("}\n\n")
	}
	fmt.Fprintf(b, "type %s struct {\n", t.goRowType())
	for _, c := range t.cols {
		fmt.Fprintf(b, "\t%s %s\n", c.goName, goFieldType(c))
	}
	b.WriteString("}\n\n")
}

type valueRenderer func(c col, v any) (string, error)

var goTypes = map[colKind]string{
	colString:     "string",
	colU8:         "uint8",
	colU16:        "uint16",
	colU32:        "uint32",
	colI32:        "int32",
	colBool:       "bool",
	colStringList: "[]string",
	colU32List:    "[]uint32",
	colPointList:  "[][2]int32",
	colPoint:      "[2]int32",
}

var goRenderers map[colKind]valueRenderer

func init() {
	goRenderers = map[colKind]valueRenderer{
		colString:     renderGoString,
		colU8:         renderGoUint,
		colU16:        renderGoUint,
		colU32:        renderGoUint,
		colI32:        renderGoInt,
		colBool:       renderGoBool,
		colStringList: renderGoStringList,
		colU32List:    renderGoUintList,
		colPointList:  renderGoPointList,
		colPoint:      renderGoPoint,
		colRecordList: renderGoRecordList,
	}
}

func goFieldType(c col) string {
	if c.kind == colRecordList {
		return "[]" + c.subName
	}
	return goTypes[c.kind]
}

func goValue(c col, v any) (string, error) {
	render, ok := goRenderers[c.kind]
	if !ok {
		return "", fmt.Errorf("unsupported column kind %d", c.kind)
	}
	return render(c, v)
}

func renderGoString(_ col, v any) (string, error) {
	s, err := valueString(v)
	if err != nil {
		return "", err
	}
	return strconv.Quote(s), nil
}

func renderGoUint(_ col, v any) (string, error) {
	u, err := valueUint(v)
	if err != nil {
		return "", err
	}
	return strconv.FormatUint(uint64(u), 10), nil
}

func renderGoInt(_ col, v any) (string, error) {
	n, err := valueInt(v)
	if err != nil {
		return "", err
	}
	return strconv.FormatInt(n, 10), nil
}

func renderGoBool(_ col, v any) (string, error) {
	ok, err := valueBool(v)
	if err != nil {
		return "", err
	}
	return strconv.FormatBool(ok), nil
}

func renderGoStringList(_ col, v any) (string, error) {
	items, err := valueStrings(v)
	if err != nil {
		return "", err
	}
	quoted := make([]string, 0, len(items))
	for _, s := range items {
		quoted = append(quoted, strconv.Quote(s))
	}
	return "[]string{" + strings.Join(quoted, ", ") + "}", nil
}

func renderGoUintList(_ col, v any) (string, error) {
	items, err := valueUints(v)
	if err != nil {
		return "", err
	}
	text := make([]string, 0, len(items))
	for _, u := range items {
		text = append(text, strconv.FormatUint(uint64(u), 10))
	}
	return "[]uint32{" + strings.Join(text, ", ") + "}", nil
}

func renderGoPointList(_ col, v any) (string, error) {
	points, err := valuePointList(v)
	if err != nil {
		return "", err
	}
	text := make([]string, 0, len(points))
	for _, p := range points {
		text = append(text, fmt.Sprintf("{%d, %d}", p[0], p[1]))
	}
	return "[][2]int32{" + strings.Join(text, ", ") + "}", nil
}

func renderGoPoint(_ col, v any) (string, error) {
	p, err := valuePoint(v)
	if err != nil {
		return "", err
	}
	return fmt.Sprintf("[2]int32{%d, %d}", p[0], p[1]), nil
}

func renderGoRecordList(c col, v any) (string, error) {
	records, err := valueRecords(v)
	if err != nil {
		return "", err
	}
	text := make([]string, 0, len(records))
	for _, rec := range records {
		fields, err := renderGoFields(c, rec)
		if err != nil {
			return "", err
		}
		text = append(text, "{"+strings.Join(fields, ", ")+"}")
	}
	return "[]" + c.subName + "{" + strings.Join(text, ", ") + "}", nil
}

func renderGoFields(c col, rec rowValues) ([]string, error) {
	if len(rec) != len(c.sub) {
		return nil, fmt.Errorf("record %s has %d fields, want %d", c.subName, len(rec), len(c.sub))
	}
	fields := make([]string, 0, len(c.sub))
	for i, sc := range c.sub {
		lit, err := goValue(sc, rec[i])
		if err != nil {
			return nil, err
		}
		fields = append(fields, lit)
	}
	return fields, nil
}

func (t *table) renderRust() ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by tools/specgen; DO NOT EDIT.\n\n")
	t.writeRustSubStructs(&b)
	t.writeRustRowStruct(&b)
	visibility, storage := "pub(crate)", "const"
	if t.rustPublicStatic {
		visibility, storage = "pub", "static"
	}
	fmt.Fprintf(&b, "%s %s %s: &[%s] = &[", visibility, storage, t.rsName, t.rsRowType())
	for _, row := range t.rows {
		record, err := t.rustRecord(row)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", t.name, err)
		}
		b.WriteString("\n    " + record + ",")
	}
	if len(t.rows) > 0 {
		b.WriteString("\n")
	}
	b.WriteString("];\n")
	return []byte(b.String()), nil
}

func (t *table) writeRustSubStructs(b *strings.Builder) {
	for _, c := range t.cols {
		if c.kind != colRecordList {
			continue
		}
		fmt.Fprintf(b, "#[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub(crate) struct %s {\n", c.subName)
		for _, sc := range c.sub {
			fmt.Fprintf(b, "    pub(crate) %s: %s,\n", sc.rsName, rustFieldType(sc))
		}
		b.WriteString("}\n\n")
	}
}

func (t *table) writeRustRowStruct(b *strings.Builder) {
	visibility := "pub(crate)"
	if t.rustPublicStatic {
		visibility = "pub"
	}
	fmt.Fprintf(b, "#[derive(Clone, Copy, Debug, PartialEq, Eq)]\n%s struct %s {\n", visibility, t.rsRowType())
	for _, c := range t.cols {
		fmt.Fprintf(b, "    %s %s: %s,\n", visibility, c.rsName, rustFieldType(c))
	}
	b.WriteString("}\n\n")
}

func (t *table) rustRecord(row rowValues) (string, error) {
	fields := make([]string, 0, len(t.cols))
	for i, c := range t.cols {
		lit, err := rustValue(c, row[i])
		if err != nil {
			return "", err
		}
		fields = append(fields, c.rsName+": "+lit)
	}
	return t.rsRowType() + " { " + strings.Join(fields, ", ") + " }", nil
}

var rustTypes = map[colKind]string{
	colString:     "&'static str",
	colU8:         "u8",
	colU16:        "u16",
	colU32:        "u32",
	colI32:        "i32",
	colBool:       "bool",
	colStringList: "&'static [&'static str]",
	colU32List:    "&'static [u32]",
	colPointList:  "&'static [(i32, i32)]",
	colPoint:      "(i32, i32)",
}

var rustRenderers map[colKind]valueRenderer

func init() {
	rustRenderers = map[colKind]valueRenderer{
		colString:     renderRustString,
		colU8:         renderRustUint,
		colU16:        renderRustUint,
		colU32:        renderRustUint,
		colI32:        renderRustInt,
		colBool:       renderRustBool,
		colStringList: renderRustStringList,
		colU32List:    renderRustUintList,
		colPointList:  renderRustPointList,
		colPoint:      renderRustPoint,
		colRecordList: renderRustRecordList,
	}
}

func rustFieldType(c col) string {
	if c.kind == colRecordList {
		return "&'static [" + c.subName + "]"
	}
	return rustTypes[c.kind]
}

func rustValue(c col, v any) (string, error) {
	render, ok := rustRenderers[c.kind]
	if !ok {
		return "", fmt.Errorf("unsupported column kind %d", c.kind)
	}
	return render(c, v)
}

