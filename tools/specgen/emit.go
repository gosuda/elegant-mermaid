func rustString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '"':
			b.WriteString(`\"`)
		case '\\':
			b.WriteString(`\\`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		default:
			if r < 0x20 || r == 0x7F {
				fmt.Fprintf(&b, `\u{%X}`, r)
				continue
			}
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

type arrayTable struct {
	name     string
	goName   string
	rsName   string
	leanName string
	goElem   string
	rsElem   string
	leanElem string
	values   []int64
}

func (a *arrayTable) renderGo() ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by tools/specgen; DO NOT EDIT.\n\npackage gen\n\n")
	fmt.Fprintf(&b, "var %s = [%d]%s{", a.goName, len(a.values), a.goElem)
	for _, v := range a.values {
		fmt.Fprintf(&b, "\n\t%d,", v)
	}
	if len(a.values) > 0 {
		b.WriteString("\n")
	}
	b.WriteString("}\n")
	return []byte(b.String()), nil
}

func (a *arrayTable) renderRust() ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by tools/specgen; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "pub(crate) const %s: [%s; %d] = [", a.rsName, a.rsElem, len(a.values))
	for _, v := range a.values {
		fmt.Fprintf(&b, "\n    %d,", v)
	}
	if len(a.values) > 0 {
		b.WriteString("\n")
	}
	b.WriteString("];\n")
	return []byte(b.String()), nil
}

func valueString(v any) (string, error) {
	s, ok := v.(string)
	if !ok {
		return "", fmt.Errorf("value %v is not a string", v)
	}
	return s, nil
}

func valueUint(v any) (uint32, error) {
	switch x := v.(type) {
	case uint8:
		return uint32(x), nil
	case uint16:
		return uint32(x), nil
	case uint32:
		return x, nil
	}
	return 0, fmt.Errorf("value %v is not unsigned", v)
}

func valueInt(v any) (int64, error) {
	switch x := v.(type) {
	case int32:
		return int64(x), nil
	case int64:
		return x, nil
	case int:
		return int64(x), nil
	}
	return 0, fmt.Errorf("value %v is not an integer", v)
}

func valueBool(v any) (bool, error) {
	b, ok := v.(bool)
	if !ok {
		return false, errors.New("value is not a bool")
	}
	return b, nil
}

func valueStrings(v any) ([]string, error) {
	s, ok := v.([]string)
	if !ok {
		return nil, errors.New("value is not a string list")
	}
	return s, nil
}

func valueUints(v any) ([]uint32, error) {
	s, ok := v.([]uint32)
	if !ok {
		return nil, errors.New("value is not a uint32 list")
	}
	return s, nil
}

func valuePointList(v any) ([][2]int32, error) {
	s, ok := v.([][2]int32)
	if !ok {
		return nil, errors.New("value is not a point list")
	}
	return s, nil
}

func valuePoint(v any) ([2]int32, error) {
	p, ok := v.([2]int32)
	if !ok {
		return [2]int32{}, errors.New("value is not a point")
	}
	return p, nil
}

func valueRecords(v any) ([][]any, error) {
	s, ok := v.([][]any)
	if !ok {
		return nil, errors.New("value is not a record list")
	}
	return s, nil
}
