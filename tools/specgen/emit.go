func rustString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '"':
			b.WriteString(`\"`)
		case '\\':
			b.WriteString(`\\`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		default:
			if r < 0x20 || r == 0x7F {
				fmt.Fprintf(&b, `\u{%X}`, r)
				continue
			}
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

const leanDecodeRows = 1024

func (t *table) renderLean() ([]byte, error) {
	var b strings.Builder
	b.WriteString("-- Code generated by tools/specgen; DO NOT EDIT.\n\n")
	writeLeanDecls(&b, t)
	if len(t.rows) > leanDecodeRows && t.leanDecodable() {
		if err := t.writeLeanDecoded(&b); err != nil {
			return nil, fmt.Errorf("%s: %w", t.name, err)
		}
		return []byte(b.String()), nil
	}
	fmt.Fprintf(&b, "def %s : Array %s :=\n  ", t.leanName, t.leanRowType())
	lits := make([]string, 0, len(t.rows)/leanLiteralRows+1)
	for _, chunk := range chunkRows(t.rows, leanLiteralRows) {
		lit, err := t.leanChunk(chunk)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", t.name, err)
		}
		lits = append(lits, lit)
	}
	if len(lits) == 0 {
		b.WriteString("#[]")
	} else {
		b.WriteString(strings.Join(lits, "\n  ++ "))
	}
	b.WriteString("\n")
	return []byte(b.String()), nil
}

const leanLiteralRows = 512

func (t *table) leanDecodable() bool {
	for _, c := range t.cols {
		if leanFieldType(c) == "" {
			return false
		}
		switch c.kind {
		case colString, colU8, colU16, colU32, colI32, colBool, colU32List:
		default:
			return false
		}
	}
	return true
}

func chunkRows(rows []rowValues, size int) [][]rowValues {
	chunks := make([][]rowValues, 0, (len(rows)+size-1)/size)
	for start := 0; start < len(rows); start += size {
		chunks = append(chunks, rows[start:min(start+size, len(rows))])
	}
	return chunks
}

func writeLeanDecls(b *strings.Builder, t *table) {
	for _, c := range t.cols {
		if c.kind != colRecordList {
			continue
		}
		fmt.Fprintf(b, "structure %s where\n", c.subName)
		for _, sc := range c.sub {
			fmt.Fprintf(b, "  %s : %s\n", leanFieldName(sc.leanName), leanFieldType(sc))
		}
		b.WriteString("\n")
	}
	fmt.Fprintf(b, "structure %s where\n", t.leanRowType())
	for _, c := range t.cols {
		fmt.Fprintf(b, "  %s : %s\n", leanFieldName(c.leanName), leanFieldType(c))
	}
	b.WriteString("\n")
}

func leanFieldName(name string) string {
	if leanKeywords[name] {
		return "«" + name + "»"
	}
	return name
}

