func (t *table) leanChunk(rows []rowValues) (string, error) {
	literals := make([]string, 0, len(rows))
	for _, row := range rows {
		record, err := t.leanRecord(row)
		if err != nil {
			return "", err
		}
		literals = append(literals, record)
	}
	return "#[" + strings.Join(literals, ", ") + "]", nil
}

func (t *table) leanRecord(row rowValues) (string, error) {
	fields := make([]string, 0, len(t.cols))
	for i, c := range t.cols {
		lit, err := leanValue(c, row[i])
		if err != nil {
			return "", err
		}
		fields = append(fields, leanFieldName(c.leanName)+" := "+lit)
	}
	return "{ " + strings.Join(fields, ", ") + " }", nil
}
