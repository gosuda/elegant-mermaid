package main

import (
	"fmt"
	"go/format"
	"strconv"
	"strings"
)

func sixelPaletteOutput() (outFile, error) {
	var palette strings.Builder
	for register := range 216 {
		fmt.Fprintf(&palette, "#%d;2;%d;%d;%d", register, 20*(register/36), 20*(register/6%6), 20*(register%6))
	}
	source := "// Code generated by tools/specgen; DO NOT EDIT.\n\npackage termgfx\n\nconst sixelPalette = " + strconv.Quote(palette.String()) + "\n"
	formatted, err := format.Source([]byte(source))
	if err != nil {
		return outFile{}, fmt.Errorf("sixel palette go: %w", err)
	}
	return outFile{path: "internal/termgfx/palette_gen.go", content: formatted}, nil
}
