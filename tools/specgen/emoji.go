type emojiSequence struct {
	scalars []uint32
	glyph   uint16
}

type emojiSeqTable struct {
	sequences []emojiSequence
}

func (t *emojiSeqTable) fileName() string { return "emojiseq" }

func (t *emojiSeqTable) renderGo() ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by tools/specgen; DO NOT EDIT.\n\npackage gen\n\n")
	b.WriteString("type EmojiSequence struct {\n\tScalars []uint32\n\tGlyph uint16\n}\n\n")
	b.WriteString("var EmojiSequences = []EmojiSequence{\n")
	for _, s := range t.sequences {
		b.WriteString("\t{[]uint32{")
		for i, cp := range s.scalars {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%d", cp)
		}
		fmt.Fprintf(&b, "}, %d},\n", s.glyph)
	}
	b.WriteString("}\n")
	return []byte(b.String()), nil
}

func (t *emojiSeqTable) renderRust() ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by tools/specgen; DO NOT EDIT.\n\n")
	b.WriteString("pub(crate) struct EmojiSequence {\n\tpub(crate) scalars: &'static [u32],\n\tpub(crate) glyph: u16,\n}\n\n")
	b.WriteString("pub(crate) static EMOJI_SEQUENCES: &[EmojiSequence] = &[\n")
	for _, s := range t.sequences {
		b.WriteString("\tEmojiSequence { scalars: &[")
		for i, cp := range s.scalars {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%d", cp)
		}
		fmt.Fprintf(&b, "], glyph: %d },\n", s.glyph)
	}
	b.WriteString("];\n")
	return []byte(b.String()), nil
}

