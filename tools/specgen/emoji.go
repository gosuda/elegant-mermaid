func collectEmojiTables(in *inputs) (*emojiSeqTable, *emojiPresentationTable, error) {
	if len(in.emojiTTF) == 0 {
		return &emojiSeqTable{}, &emojiPresentationTable{}, nil
	}
	font, err := sfnt.Parse(in.emojiTTF)
	if err != nil {
		return nil, nil, fmt.Errorf("parse emoji font: %w", err)
	}
	glyphCP, err := emojiGlyphCPs(font)
	if err != nil {
		return nil, nil, err
	}
	gsub, err := extractGSUB(in.emojiTTF)
	if err != nil {
		return nil, nil, err
	}
	lookups, ccmp, err := parseGSUBLookups(gsub)
	if err != nil {
		return nil, nil, err
	}
	seqs, err := collectCCMPSequences(lookups, ccmp, glyphCP)
	if err != nil {
		return nil, nil, err
	}
	presentation, err := buildEmojiPresentationRanges(in.emoji)
	if err != nil {
		return nil, nil, err
	}
	slices.SortFunc(seqs, compareEmojiSequences)
	return &emojiSeqTable{sequences: seqs}, &emojiPresentationTable{ranges: presentation}, nil
}

func collectCCMPSequences(lookups []gsubLookup, ccmp []int, glyphCP map[uint16]uint32) ([]emojiSequence, error) {
	var seqs []emojiSequence
	for _, li := range ccmp {
		if li < 0 || li >= len(lookups) {
			return nil, fmt.Errorf("ccmp lookup %d out of range", li)
		}
		more, err := lookupSequences(lookups[li], li, glyphCP)
		if err != nil {
			return nil, err
		}
		seqs = append(seqs, more...)
	}
	return seqs, nil
}

func lookupSequences(lk gsubLookup, li int, glyphCP map[uint16]uint32) ([]emojiSequence, error) {
	var seqs []emojiSequence
	for _, sub := range lk.subtables {
		more, err := subtableSequences(lk.lookupType, li, sub, glyphCP)
		if err != nil {
			return nil, err
		}
		seqs = append(seqs, more...)
	}
	return seqs, nil
}

func subtableSequences(lookupType, li int, sub []byte, glyphCP map[uint16]uint32) ([]emojiSequence, error) {
	switch lookupType {
	case 4:
		more, err := ligatureSequences(sub, glyphCP)
		if err != nil {
			return nil, fmt.Errorf("ccmp lookup %d ligatures: %w", li, err)
		}
		return more, nil
	case 7:
		return extensionSequences(li, sub, glyphCP)
	default:
		return nil, nil
	}
}

func extensionSequences(li int, sub []byte, glyphCP map[uint16]uint32) ([]emojiSequence, error) {
	innerType, inner, err := extensionInner(sub)
	if err != nil {
		return nil, fmt.Errorf("ccmp lookup %d extension: %w", li, err)
	}
	if innerType != 4 {
		return nil, nil
	}
	more, err := ligatureSequences(inner, glyphCP)
	if err != nil {
		return nil, fmt.Errorf("ccmp lookup %d ligatures: %w", li, err)
	}
	return more, nil
}

func compareEmojiSequences(a, b emojiSequence) int {
	for i := 0; i < len(a.scalars) && i < len(b.scalars); i++ {
		if c := cmp.Compare(a.scalars[i], b.scalars[i]); c != 0 {
			return c
		}
	}
	if c := cmp.Compare(len(a.scalars), len(b.scalars)); c != 0 {
		return c
	}
	return cmp.Compare(a.glyph, b.glyph)
}

func emojiGlyphCPs(font *sfnt.Font) (map[uint16]uint32, error) {
	out := make(map[uint16]uint32)
	for cp := rune(0); cp <= 0x10FFFF; cp++ {
		if cp >= 0xD800 && cp <= 0xDFFF {
			continue
		}
		idx, err := font.GlyphIndex(nil, cp)
		if err != nil {
			return nil, fmt.Errorf("cmap lookup U+%04X: %w", cp, err)
		}
		if idx == 0 {
			continue
		}
		if _, ok := out[uint16(idx)]; !ok {
			out[uint16(idx)] = uint32(cp)
		}
	}
	return out, nil
}

func gsubU16(b []byte, at int) (uint16, error) {
	if at < 0 || at+2 > len(b) {
		return 0, fmt.Errorf("gsub read at %d over %d bytes", at, len(b))
	}
	return binary.BigEndian.Uint16(b[at:]), nil
}

func gsubU32(b []byte, at int) (uint32, error) {
	if at < 0 || at+4 > len(b) {
		return 0, fmt.Errorf("gsub read at %d over %d bytes", at, len(b))
	}
	return binary.BigEndian.Uint32(b[at:]), nil
}

func extractGSUB(fontBytes []byte) ([]byte, error) {
	if len(fontBytes) < 12 {
		return nil, fmt.Errorf("font has %d bytes", len(fontBytes))
	}
	count, err := gsubU16(fontBytes, 4)
	if err != nil {
		return nil, err
	}
	for i := 0; i < int(count); i++ {
		base := 12 + i*16
		if base+16 > len(fontBytes) {
			return nil, fmt.Errorf("font directory ends at entry %d", i)
		}
		if string(fontBytes[base:base+4]) != "GSUB" {
			continue
		}
		off, err := gsubU32(fontBytes, base+8)
		if err != nil {
			return nil, err
		}
		length, err := gsubU32(fontBytes, base+12)
		if err != nil {
			return nil, err
		}
		if uint64(off)+uint64(length) > uint64(len(fontBytes)) {
			return nil, fmt.Errorf("GSUB spans outside font")
		}
		return fontBytes[off : off+length], nil
	}
	return nil, fmt.Errorf("font has no GSUB table")
}

type gsubFeature struct {
	tag     string
	lookups []int
}

type gsubLookup struct {
	lookupType int
	subtables  [][]byte
}

func parseGSUBLookups(gsub []byte) ([]gsubLookup, []int, error) {
	major, err := gsubU16(gsub, 0)
	if err != nil {
		return nil, nil, err
	}
	if major != 1 {
		return nil, nil, fmt.Errorf("GSUB major version %d", major)
	}
	scriptOff, err := gsubU16(gsub, 4)
	if err != nil {
		return nil, nil, err
	}
	featureOff, err := gsubU16(gsub, 6)
	if err != nil {
		return nil, nil, err
	}
	lookupOff, err := gsubU16(gsub, 8)
	if err != nil {
		return nil, nil, err
	}
	features, err := parseGSUBFeatures(gsub, int(featureOff))
	if err != nil {
		return nil, nil, err
	}
	ccmp, err := dfltCCMPLookups(gsub, int(scriptOff), features)
	if err != nil {
		return nil, nil, err
	}
	lookups, err := parseGSUBLookupList(gsub, int(lookupOff))
	if err != nil {
		return nil, nil, err
	}
	return lookups, ccmp, nil
}

func parseGSUBFeatures(gsub []byte, at int) ([]gsubFeature, error) {
	count, err := gsubU16(gsub, at)
	if err != nil {
		return nil, err
	}
	out := make([]gsubFeature, 0, count)
	for i := 0; i < int(count); i++ {
		base := at + 2 + i*6
		if base+6 > len(gsub) {
			return nil, fmt.Errorf("feature record %d out of range", i)
		}
		tag := string(gsub[base : base+4])
		off, err := gsubU16(gsub, base+4)
		if err != nil {
			return nil, err
		}
		fb := at + int(off)
		params, err := gsubU16(gsub, fb)
		if err != nil {
			return nil, err
		}
		_ = params
		lookupCount, err := gsubU16(gsub, fb+2)
		if err != nil {
			return nil, err
		}
		feature := gsubFeature{tag: tag}
		for j := 0; j < int(lookupCount); j++ {
			li, err := gsubU16(gsub, fb+4+j*2)
			if err != nil {
				return nil, err
			}
			feature.lookups = append(feature.lookups, int(li))
		}
		out = append(out, feature)
	}
	return out, nil
}

func dfltCCMPLookups(gsub []byte, at int, features []gsubFeature) ([]int, error) {
	count, err := gsubU16(gsub, at)
	if err != nil {
		return nil, err
	}
	for i := 0; i < int(count); i++ {
		isDFLT, lookups, err := dfltScriptEntry(gsub, at, i, features)
		if err != nil {
			return nil, err
		}
		if !isDFLT {
			continue
		}
		if lookups != nil {
			return lookups, nil
		}
		break
	}
	return ccmpFeatureLookups(features)
}

func dfltScriptEntry(gsub []byte, at, i int, features []gsubFeature) (bool, []int, error) {
	base := at + 2 + i*6
	if base+6 > len(gsub) {
		return false, nil, fmt.Errorf("script record %d out of range", i)
	}
	if string(gsub[base:base+4]) != "DFLT" {
		return false, nil, nil
	}
	off, err := gsubU16(gsub, base+4)
	if err != nil {
		return false, nil, err
	}
	sb := at + int(off)
	defOff, err := gsubU16(gsub, sb)
	if err != nil {
		return false, nil, err
	}
	if defOff == 0 {
		return true, nil, nil
	}
	lookups, err := dfltLangCCMP(gsub, sb+int(defOff), features)
	if err != nil {
		return false, nil, err
	}
	return true, lookups, nil
}

func dfltLangCCMP(gsub []byte, lb int, features []gsubFeature) ([]int, error) {
	featureCount, err := gsubU16(gsub, lb+4)
	if err != nil {
		return nil, err
	}
	for j := 0; j < int(featureCount); j++ {
		fi, err := gsubU16(gsub, lb+6+j*2)
		if err != nil {
			return nil, err
		}
		if int(fi) < len(features) && features[fi].tag == "ccmp" {
			return slices.Clone(features[fi].lookups), nil
		}
	}
	return nil, nil
}

func ccmpFeatureLookups(features []gsubFeature) ([]int, error) {
	for _, f := range features {
		if f.tag == "ccmp" {
			return slices.Clone(f.lookups), nil
		}
	}
	return nil, fmt.Errorf("GSUB has no ccmp feature")
}

func parseGSUBLookupList(gsub []byte, at int) ([]gsubLookup, error) {
	count, err := gsubU16(gsub, at)
	if err != nil {
		return nil, err
	}
	out := make([]gsubLookup, 0, count)
	for i := 0; i < int(count); i++ {
		lk, err := parseGSUBLookup(gsub, at, i)
		if err != nil {
			return nil, err
		}
		out = append(out, lk)
	}
	return out, nil
}

func parseGSUBLookup(gsub []byte, at, i int) (gsubLookup, error) {
	var lookup gsubLookup
	off, err := gsubU16(gsub, at+2+i*2)
	if err != nil {
		return lookup, err
	}
	lb := at + int(off)
	lookupType, err := gsubU16(gsub, lb)
	if err != nil {
		return lookup, err
	}
	flags, err := gsubU16(gsub, lb+2)
	if err != nil {
		return lookup, err
	}
	subCount, err := gsubU16(gsub, lb+4)
	if err != nil {
		return lookup, err
	}
	lookup.lookupType = int(lookupType)
	next := lb + 6 + int(subCount)*2
	if flags&0x0010 != 0 {
		next += 2
	}
	if next > len(gsub) {
		return lookup, fmt.Errorf("lookup %d spans outside GSUB", i)
	}
	tables, err := lookupSubtables(gsub, lb, i, int(subCount))
	if err != nil {
		return lookup, err
	}
	lookup.subtables = tables
	return lookup, nil
}

func lookupSubtables(gsub []byte, lb, i, subCount int) ([][]byte, error) {
	var tables [][]byte
	for j := 0; j < subCount; j++ {
		so, err := gsubU16(gsub, lb+6+j*2)
		if err != nil {
			return nil, err
		}
		sb := lb + int(so)
		if sb > len(gsub) {
			return nil, fmt.Errorf("lookup %d subtable %d spans outside GSUB", i, j)
		}
		tables = append(tables, gsub[sb:])
	}
	return tables, nil
}

func coverageGlyphs(sub []byte, off int) ([]uint16, error) {
	format, err := gsubU16(sub, off)
	if err != nil {
		return nil, err
	}
	switch format {
	case 1:
		return coverageList(sub, off)
	case 2:
		return coverageRanges(sub, off)
	default:
		return nil, fmt.Errorf("coverage format %d", format)
	}
}

func coverageList(sub []byte, off int) ([]uint16, error) {
	count, err := gsubU16(sub, off+2)
	if err != nil {
		return nil, err
	}
	out := make([]uint16, 0, count)
	for i := 0; i < int(count); i++ {
		g, err := gsubU16(sub, off+4+i*2)
		if err != nil {
			return nil, err
		}
		out = append(out, g)
	}
	return out, nil
}

func coverageRanges(sub []byte, off int) ([]uint16, error) {
	rangeCount, err := gsubU16(sub, off+2)
	if err != nil {
		return nil, err
	}
	var out []uint16
	for i := 0; i < int(rangeCount); i++ {
		more, err := coverageRange(sub, off+4+i*6)
		if err != nil {
			return nil, err
		}
		out = append(out, more...)
	}
	return out, nil
}

func coverageRange(sub []byte, at int) ([]uint16, error) {
	start, err := gsubU16(sub, at)
	if err != nil {
		return nil, err
	}
	end, err := gsubU16(sub, at+2)
	if err != nil {
		return nil, err
	}
	if end < start {
		return nil, nil
	}
	out := make([]uint16, 0, end-start+1)
	for g := start; g <= end; g++ {
		out = append(out, g)
	}
	return out, nil
}

func ligatureSequences(sub []byte, glyphCP map[uint16]uint32) ([]emojiSequence, error) {
	setCount, coverage, err := readLigatureHeader(sub)
	if err != nil {
		return nil, err
	}
	var out []emojiSequence
	for i := 0; i < int(setCount); i++ {
		more, err := ligatureSetSequences(sub, i, coverage[i], glyphCP)
		if err != nil {
			return nil, err
		}
		out = append(out, more...)
	}
	return out, nil
}

func readLigatureHeader(sub []byte) (uint16, []uint16, error) {
	format, err := gsubU16(sub, 0)
	if err != nil {
		return 0, nil, err
	}
	if format != 1 {
		return 0, nil, fmt.Errorf("ligature format %d", format)
	}
	covOff, err := gsubU16(sub, 2)
	if err != nil {
		return 0, nil, err
	}
	setCount, err := gsubU16(sub, 4)
	if err != nil {
		return 0, nil, err
	}
	coverage, err := coverageGlyphs(sub, int(covOff))
	if err != nil {
		return 0, nil, err
	}
	if len(coverage) != int(setCount) {
		return 0, nil, fmt.Errorf("ligature coverage has %d glyphs for %d sets", len(coverage), setCount)
	}
	return setCount, coverage, nil
}

func ligatureSetSequences(sub []byte, i int, firstGlyph uint16, glyphCP map[uint16]uint32) ([]emojiSequence, error) {
	setOff, err := gsubU16(sub, 6+i*2)
	if err != nil {
		return nil, err
	}
	sb := int(setOff)
	ligCount, err := gsubU16(sub, sb)
	if err != nil {
		return nil, err
	}
	first, ok := glyphCP[firstGlyph]
	var out []emojiSequence
	for k := 0; k < int(ligCount); k++ {
		seq, err := ligatureEntry(sub, sb, k, first, ok, glyphCP)
		if err != nil {
			return nil, err
		}
		if seq != nil {
			out = append(out, *seq)
		}
	}
	return out, nil
}

func ligatureEntry(sub []byte, sb, k int, first uint32, ok bool, glyphCP map[uint16]uint32) (*emojiSequence, error) {
	ligOff, err := gsubU16(sub, sb+2+k*2)
	if err != nil {
		return nil, err
	}
	lb := sb + int(ligOff)
	ligGlyph, err := gsubU16(sub, lb)
	if err != nil {
		return nil, err
	}
	compCount, err := gsubU16(sub, lb+2)
	if err != nil {
		return nil, err
	}
	if compCount < 1 {
		return nil, fmt.Errorf("ligature with %d components", compCount)
	}
	if !ok {
		return nil, nil
	}
	return ligatureComponents(sub, lb, ligGlyph, first, compCount, glyphCP)
}

func ligatureComponents(sub []byte, lb int, ligGlyph uint16, first uint32, compCount uint16, glyphCP map[uint16]uint32) (*emojiSequence, error) {
	seq := make([]uint32, 0, compCount)
	seq = append(seq, first)
	for c := 0; c < int(compCount)-1; c++ {
		g, err := gsubU16(sub, lb+4+c*2)
		if err != nil {
			return nil, err
		}
		cp, ok := glyphCP[g]
		if !ok {
			return nil, nil
		}
		seq = append(seq, cp)
	}
	return &emojiSequence{scalars: seq, glyph: ligGlyph}, nil
}

func extensionInner(sub []byte) (int, []byte, error) {
	format, err := gsubU16(sub, 0)
	if err != nil {
		return 0, nil, err
	}
	if format != 1 {
		return 0, nil, fmt.Errorf("extension format %d", format)
	}
	extType, err := gsubU16(sub, 2)
	if err != nil {
		return 0, nil, err
	}
	extOff, err := gsubU32(sub, 4)
	if err != nil {
		return 0, nil, err
	}
	if int(extOff) >= len(sub) {
		return 0, nil, fmt.Errorf("extension offset %d over %d bytes", extOff, len(sub))
	}
	return int(extType), sub[extOff:], nil
}

func buildEmojiPresentationRanges(emojiData []byte) ([]tableRange, error) {
	lines, err := parseUCD(emojiData)
	if err != nil {
		return nil, fmt.Errorf("emoji-data.txt: %w", err)
	}
	vals := newScalarArray(0)
	for _, ln := range lines {
		if ln.field(1) == "Emoji_Presentation" {
			assignRange(vals, ln.lo, ln.hi, 1)
		}
	}
	return compressSparse(vals), nil
}
