func renderLeanCellNatList(_ col, v any) (string, error) {
	items, err := valueUints(v)
	if err != nil {
		return "", err
	}
	text := make([]string, 0, len(items))
	for _, u := range items {
		text = append(text, strconv.FormatUint(uint64(u), 10))
	}
	return strings.Join(text, string(leanItemSep)), nil
}

func leanEscapeText(s string) string {
	var b strings.Builder
	for _, r := range s {
		if r == '%' || r == leanItemSep || r == leanFieldSep || r == leanRowSep || r == '\n' || r == '\t' || r == '\r' {
			fmt.Fprintf(&b, "%%%02X", r)
			continue
		}
		b.WriteRune(r)
	}
	return b.String()
}

func chunkInt64(values []int64, size int) [][]int64 {
	chunks := make([][]int64, 0, (len(values)+size-1)/size)
	for start := 0; start < len(values); start += size {
		chunks = append(chunks, values[start:min(start+size, len(values))])
	}
	return chunks
}
