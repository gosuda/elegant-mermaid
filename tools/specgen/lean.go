package main

import (
	"fmt"
	"strconv"
	"strings"
)

const leanDecodeRows = 1024

const leanHeader = "-- Code generated by tools/specgen; DO NOT EDIT.\n\n"

func (t *table) renderLean() ([]byte, error) {
	body, err := t.leanBody()
	if err != nil {
		return nil, err
	}
	return []byte(leanHeader + body), nil
}

func (t *table) leanBody() (string, error) {
	var b strings.Builder
	writeLeanDecls(&b, t)
	if len(t.rows) > leanDecodeRows && t.leanDecodable() {
		if err := t.writeLeanDecoded(&b); err != nil {
			return "", fmt.Errorf("%s: %w", t.name, err)
		}
		return b.String(), nil
	}
	fmt.Fprintf(&b, "%s %s : Array %s :=\n  ", t.leanDefKeyword(), t.leanName, t.leanRowType())
	lits := make([]string, 0, len(t.rows)/leanLiteralRows+1)
	for _, chunk := range chunkRows(t.rows, leanLiteralRows) {
		lit, err := t.leanChunk(chunk)
		if err != nil {
			return "", fmt.Errorf("%s: %w", t.name, err)
		}
		lits = append(lits, lit)
	}
	if len(lits) == 0 {
		b.WriteString("#[]")
	} else {
		b.WriteString(strings.Join(lits, "\n  ++ "))
	}
	b.WriteString("\n")
	return b.String(), nil
}

func (t *table) leanDefKeyword() string {
	if t.leanOpaque {
		return "opaque"
	}
	return "def"
}

const leanLiteralRows = 512

func (t *table) leanDecodable() bool {
	for _, c := range t.cols {
		if leanFieldType(c) == "" {
			return false
		}
		switch c.kind {
		case colString, colU8, colU16, colU32, colI32, colBool, colU32List:
		default:
			return false
		}
	}
	return true
}

func chunkRows(rows []rowValues, size int) [][]rowValues {
	chunks := make([][]rowValues, 0, (len(rows)+size-1)/size)
	for start := 0; start < len(rows); start += size {
		chunks = append(chunks, rows[start:min(start+size, len(rows))])
	}
	return chunks
}

func writeLeanDecls(b *strings.Builder, t *table) {
	for _, c := range t.cols {
		if c.kind != colRecordList {
			continue
		}
		fmt.Fprintf(b, "structure %s where\n", c.subName)
		for _, sc := range c.sub {
			fmt.Fprintf(b, "  %s : %s\n", leanFieldName(sc.leanName), leanFieldType(sc))
		}
		b.WriteString("\n")
	}
	fmt.Fprintf(b, "structure %s where\n", t.leanRowType())
	for _, c := range t.cols {
		fmt.Fprintf(b, "  %s : %s\n", leanFieldName(c.leanName), leanFieldType(c))
	}
	b.WriteString("\n")
}

func leanFieldName(name string) string {
	if leanKeywords[name] {
		return "«" + name + "»"
	}
	return name
}

var leanKeywords = map[string]bool{
	"class": true, "def": true, "where": true, "match": true, "let": true,
	"in": true, "if": true, "then": true, "else": true, "end": true,
	"fun": true, "do": true, "at": true, "by": true, "from": true,
	"have": true, "show": true, "type": true, "structure": true, "instance": true,
}

var leanTypes = map[colKind]string{
	colString:     "String",
	colU8:         "Nat",
	colU16:        "Nat",
	colU32:        "Nat",
	colI32:        "Int",
	colBool:       "Bool",
	colStringList: "List String",
	colU32List:    "List Nat",
	colPointList:  "List (Int × Int)",
	colPoint:      "Int × Int",
}

var leanRenderers map[colKind]valueRenderer

func init() {
	leanRenderers = map[colKind]valueRenderer{
		colString:     renderLeanString,
		colU8:         renderLeanNat,
		colU16:        renderLeanNat,
		colU32:        renderLeanNat,
		colI32:        renderLeanInt,
		colBool:       renderLeanBool,
		colStringList: renderLeanStringList,
		colU32List:    renderLeanNatList,
		colPointList:  renderLeanPointList,
		colPoint:      renderLeanPoint,
		colRecordList: renderLeanRecordList,
	}
}

func leanFieldType(c col) string {
	if c.kind == colRecordList {
		return "List " + c.subName
	}
	return leanTypes[c.kind]
}

func leanValue(c col, v any) (string, error) {
	render, ok := leanRenderers[c.kind]
	if !ok {
		return "", fmt.Errorf("unsupported column kind %d", c.kind)
	}
	return render(c, v)
}

func (t *table) leanChunk(rows []rowValues) (string, error) {
	literals := make([]string, 0, len(rows))
	for _, row := range rows {
		record, err := t.leanRecord(row)
		if err != nil {
			return "", err
		}
		literals = append(literals, record)
	}
	return "#[" + strings.Join(literals, ", ") + "]", nil
}

func (t *table) leanRecord(row rowValues) (string, error) {
	fields := make([]string, 0, len(t.cols))
	for i, c := range t.cols {
		lit, err := leanValue(c, row[i])
		if err != nil {
			return "", err
		}
		fields = append(fields, leanFieldName(c.leanName)+" := "+lit)
	}
	return "{ " + strings.Join(fields, ", ") + " }", nil
}

