package main

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

type outFile struct {
	path    string
	content []byte
}

type renderable interface {
	fileName() string
	renderGo() ([]byte, error)
	renderRust() ([]byte, error)
	renderLean() ([]byte, error)
}

func (t *table) fileName() string      { return t.name }
func (a *arrayTable) fileName() string { return a.name }

func generateRoot(root string, stdout io.Writer) error {
	files, err := buildOutputs(root)
	if err != nil {
		return err
	}
	if err := writeOutputs(root, files); err != nil {
		return err
	}
	_, err = fmt.Fprintf(stdout, "specgen: wrote %d files\n", len(files))
	return err
}

func buildOutputs(root string) ([]outFile, error) {
	in, err := loadInputs(root)
	if err != nil {
		return nil, err
	}
	return buildOutputsFrom(root, in)
}

func buildOutputsFrom(root string, in *inputs) ([]outFile, error) {
	files, err := buildGeneratedFiles(in)
	if err != nil {
		return nil, err
	}
	copied, err := buildCopies(root)
	if err != nil {
		return nil, err
	}
	extra, err := buildExtras(in)
	if err != nil {
		return nil, err
	}
	return append(append(files, copied...), extra...), nil
}

func buildGeneratedFiles(in *inputs) ([]outFile, error) {
	tables, err := buildGeneratedTables(in)
	if err != nil {
		return nil, err
	}
	var files []outFile
	modules := make([]string, 0, len(tables))
	for _, t := range tables {
		rendered, err := renderOne(t)
		if err != nil {
			return nil, err
		}
		files = append(files, rendered...)
		modules = append(modules, t.fileName())
	}
	rsMod, err := formatRustMod(modSource(modules))
	if err != nil {
		return nil, err
	}
	files = append(files, outFile{path: "crates/elegant-mermaid/src/gen/mod.rs", content: rsMod})
	return files, nil
}

func renderOne(t renderable) ([]outFile, error) {
	goSrc, err := t.renderGo()
	if err != nil {
		return nil, err
	}
	formattedGo, err := format.Source(goSrc)
	if err != nil {
		return nil, fmt.Errorf("%s go: %w", t.fileName(), err)
	}
	rsSrc, err := t.renderRust()
	if err != nil {
		return nil, err
	}
	formattedRs, err := formatRust(rsSrc)
	if err != nil {
		return nil, fmt.Errorf("%s rust: %w", t.fileName(), err)
	}
	lnSrc, err := t.renderLean()
	if err != nil {
		return nil, err
	}
	return []outFile{
		{path: "internal/gen/" + t.fileName() + ".go", content: formattedGo},
		{path: "crates/elegant-mermaid/src/gen/" + t.fileName() + ".rs", content: formattedRs},
		{path: "proofs/Elegant/Gen/" + exportName(t.fileName()) + ".lean", content: lnSrc},
	}, nil
}

func modSource(modules []string) []byte {
	var b strings.Builder
	b.WriteString("// Code generated by tools/specgen; DO NOT EDIT.\n\n#![allow(dead_code)]\n\n")
	for _, name := range modules {
		fmt.Fprintf(&b, "pub(crate) mod %s;\n", name)
	}
	return []byte(b.String())
}

func formatRust(src []byte) ([]byte, error) {
	return formatRustFile(src, "file.rs")
}

func formatRustMod(src []byte) ([]byte, error) {
	return formatRustWithConfig(src, "mod.rs", "--config", "skip_children=true")
}

func formatRustFile(src []byte, name string) ([]byte, error) {
	return formatRustWithConfig(src, name)
}

func formatRustWithConfig(src []byte, name string, extra ...string) ([]byte, error) {
	dir, err := os.MkdirTemp("", "specgen-rustfmt")
	if err != nil {
		return nil, err
	}
	defer func() { _ = os.RemoveAll(dir) }()
	path := filepath.Join(dir, name)
	if err := os.WriteFile(path, src, 0o644); err != nil {
		return nil, err
	}
	args := append([]string{"--edition", "2024", "--emit", "files"}, extra...)
	args = append(args, path)
	cmd := exec.Command("rustfmt", args...)
	if out, err := cmd.CombinedOutput(); err != nil {
		return nil, fmt.Errorf("rustfmt: %w: %s", err, out)
	}
	return os.ReadFile(path)
}

func writeOutputs(root string, files []outFile) error {
	for _, f := range files {
		abs := filepath.Join(root, filepath.FromSlash(f.path))
		if err := os.MkdirAll(filepath.Dir(abs), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(abs, f.content, 0o644); err != nil {
			return err
		}
	}
	return nil
}

func buildCopies(root string) ([]outFile, error) {
	copies := []struct {
		src string
		dst []string
	}{
		{"spec/data/fonts/Inter-Regular.ttf", []string{"raster/fonts/Inter-Regular.ttf", "crates/elegant-mermaid/assets/fonts/Inter-Regular.ttf"}},
		{"spec/data/fonts/Inter-SemiBold.ttf", []string{"raster/fonts/Inter-SemiBold.ttf", "crates/elegant-mermaid/assets/fonts/Inter-SemiBold.ttf"}},
		{"spec/data/fonts/LICENSE.txt", []string{"raster/fonts/LICENSE.txt", "crates/elegant-mermaid/assets/fonts/LICENSE.txt"}},
		{"spec/data/fonts/Inter-Regular.woff2", []string{"playground/static/fonts/Inter-Regular.woff2"}},
		{"spec/data/fonts/Inter-SemiBold.woff2", []string{"playground/static/fonts/Inter-SemiBold.woff2"}},
		{"README.md", []string{"crates/elegant-mermaid/README.md", "crates/elegant-mermaid-cli/README.md"}},
		{"LICENSE", []string{"crates/elegant-mermaid/LICENSE", "crates/elegant-mermaid-cli/LICENSE"}},
		{"THIRD_PARTY_NOTICES.md", []string{"crates/elegant-mermaid/THIRD_PARTY_NOTICES.md", "crates/elegant-mermaid-cli/THIRD_PARTY_NOTICES.md"}},
	}
	var files []outFile
	for _, copy := range copies {
		data, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(copy.src)))
		if errors.Is(err, os.ErrNotExist) {
			continue
		}
		if err != nil {
			return nil, err
		}
		for _, dst := range copy.dst {
			files = append(files, outFile{path: dst, content: data})
		}
	}
	return files, nil
}

func compareOutputs(root string, files []outFile) ([]string, error) {
	var problems []string
	for _, f := range files {
		abs := filepath.Join(root, filepath.FromSlash(f.path))
		actual, err := os.ReadFile(abs)
		if errors.Is(err, os.ErrNotExist) {
			problems = append(problems, "missing "+f.path)
			continue
		}
		if err != nil {
			return nil, err
		}
		if !bytes.Equal(actual, f.content) {
			problems = append(problems, "differs "+f.path)
		}
	}
	return problems, nil
}
