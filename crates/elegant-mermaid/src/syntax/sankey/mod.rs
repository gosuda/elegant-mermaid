//! Syntax of the `sankey` kind: lexer modes, grammar, and diagnostics of
//! `spec/grammar/sankey.md`.

pub mod ast;
pub mod lexer;
pub mod parser;

pub use parser::parse;

use crate::diag::{Diagnostic, Severity};

pub(crate) const C_UNEXPECTED: &str = "sankey/unexpected-token";

pub(crate) const C_UNKNOWN: &str = "sankey/unknown-statement";

pub(crate) const C_UNTERMINATED: &str = "sankey/unterminated";

pub(crate) fn diagnostic(
    code: &'static str,
    message: String,
    span: crate::source::Span,
) -> Diagnostic {
    Diagnostic {
        code,
        severity: Severity::Error,
        message,
        span,
        related: Vec::new(),
        help: crate::r#gen::diagnostics::DIAGNOSTICS
            .iter()
            .find(|row| row.code == code)
            .map_or("", |row| row.help)
            .into(),
        fixes: Vec::new(),
    }
}
